// Generate trusted prices/variants from the same catalog used by the storefront.
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const compiledModule = new Module(__filename);
compiledModule._compile(
  ts.transpileModule(fs.readFileSync('src/data/products.ts', 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS },
  }).outputText,
  __filename,
);
const quote = (value) => "'" + value.replaceAll("'", "''") + "'";
const rows = compiledModule.exports.PRODUCTS.filter((p) => p.price !== null).map(
  (p) =>
    `(${p.id},${quote(
      JSON.stringify({
        title: p.title,
        image: p.image,
        price_cents: Math.round(p.price * 100),
        sizes: p.sizes,
        colors: p.colors.map((c) => c.name),
      }),
    )}::jsonb,true)`,
);
fs.writeFileSync(
  'supabase/setup/checkout-catalog.sql',
  '-- Generated by node scripts/export-checkout-catalog.cjs. Run after the orders migration.\nbegin;\n' +
    'update private.checkout_products set active=false;\n' +
    'insert into private.checkout_products(id,data,active) values\n' +
    rows.join(',\n') +
    '\non conflict(id) do update set data=excluded.data,active=true;\ncommit;\n',
);
console.log('Generated supabase/setup/checkout-catalog.sql');
